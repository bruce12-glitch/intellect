import { FastifyInstance } from 'fastify';
import { z } from 'zod';
import { AppError } from '../utils/errors';
import { ContentSourceType, ContentStatus } from '@intellect/shared';

const createContentSchema = z.object({
  title: z.string().min(1).max(500),
  url: z.string().url().optional(),
  sourceType: z.nativeEnum(ContentSourceType),
  sourceId: z.string().optional(),
  rawContent: z.string().optional(),
  metadata: z.record(z.unknown()).optional(),
});

const updateContentSchema = z.object({
  title: z.string().min(1).max(500).optional(),
  url: z.string().url().optional(),
  rawContent: z.string().optional(),
  metadata: z.record(z.unknown()).optional(),
  tags: z.array(z.string()).optional(),
});

const querySchema = z.object({
  page: z.coerce.number().positive().default(1),
  limit: z.coerce.number().positive().max(100).default(20),
  sourceType: z.nativeEnum(ContentSourceType).optional(),
  status: z.nativeEnum(ContentStatus).optional(),
  tag: z.string().optional(),
  search: z.string().optional(),
  sortBy: z.enum(['created', 'updated', 'title']).default('created'),
  sortOrder: z.enum(['asc', 'desc']).default('desc'),
});

export async function contentRoutes(app: FastifyInstance) {
  // Get all content items
  app.get('/', {
    schema: {
      querystring: querySchema,
    },
  }, async (request, reply) => {
    const { page, limit, sourceType, status, tag, search, sortBy, sortOrder } = request.query as z.infer<typeof querySchema>;
    const userId = request.user!.id;
    
    const where: Record<string, unknown> = { userId };
    
    if (sourceType) where.sourceType = sourceType;
    if (status) where.status = status;
    if (tag) where.tags = { some: { name: tag } };
    if (search) {
      where.OR = [
        { title: { contains: search, mode: 'insensitive' } },
        { summary: { contains: search, mode: 'insensitive' } },
        { rawContent: { contains: search, mode: 'insensitive' } },
      ];
    }
    
    const [items, total] = await Promise.all([
      app.prisma.contentItem.findMany({
        where,
        include: {
          tags: true,
          _count: { select: { connectionsFrom: true, connectionsTo: true } },
        },
        orderBy: { [sortBy]: sortOrder },
        skip: (page - 1) * limit,
        take: limit,
      }),
      app.prisma.contentItem.count({ where }),
    ]);
    
    return {
      success: true,
      data: items,
      meta: {
        timestamp: new Date().toISOString(),
        requestId: request.id,
        version: '1.0.0',
        pagination: {
          page,
          limit,
          total,
          totalPages: Math.ceil(total / limit),
        },
      },
    };
  });

  // Get single content item
  app.get('/:id', async (request, reply) => {
    const { id } = request.params as { id: string };
    const userId = request.user!.id;
    
    const item = await app.prisma.contentItem.findFirst({
      where: { id, userId },
      include: {
        tags: true,
        connectionsFrom: { include: { targetContent: { include: { tags: true } } } },
        connectionsTo: { include: { sourceContent: { include: { tags: true } } } },
        summaries: { orderBy: { createdAt: 'desc' }, take: 1 },
        quizzes: { include: { _count: { select: { attempts: true } } } },
      },
    });
    
    if (!item) {
      throw AppError.notFound('Content item not found');
    }
    
    return {
      success: true,
      data: item,
      meta: {
        timestamp: new Date().toISOString(),
        requestId: request.id,
        version: '1.0.0',
      },
    };
  });

  // Create content item
  app.post('/', {
    schema: {
      body: createContentSchema,
    },
  }, async (request, reply) => {
    const data = request.body as z.infer<typeof createContentSchema>;
    const userId = request.user!.id;
    
    // If URL provided, check for duplicate
    if (data.url) {
      const existing = await app.prisma.contentItem.findFirst({
        where: { userId, url: data.url },
      });
      if (existing) {
        throw AppError.conflict('Content with this URL already exists');
      }
    }
    
    const item = await app.prisma.contentItem.create({
      data: {
        ...data,
        userId,
        status: data.rawContent ? ContentStatus.PENDING : ContentStatus.PENDING,
        tags: data.tags ? {
          connectOrCreate: data.tags.map(name => ({
            where: { userId_name: { userId, name } },
            create: { userId, name, color: '#3B82F6', isAutoGenerated: false },
          })),
        } : undefined,
      },
      include: { tags: true },
    });
    
    // Queue for processing if raw content provided
    if (data.rawContent) {
      await app.redis.lpush('content-processing-queue', JSON.stringify({ contentId: item.id }));
    }
    
    return reply.status(201).send({
      success: true,
      data: item,
      meta: {
        timestamp: new Date().toISOString(),
        requestId: request.id,
        version: '1.0.0',
      },
    });
  });

  // Update content item
  app.patch('/:id', {
    schema: {
      body: updateContentSchema,
    },
  }, async (request, reply) => {
    const { id } = request.params as { id: string };
    const data = request.body as z.infer<typeof updateContentSchema>;
    const userId = request.user!.id;
    
    const item = await app.prisma.contentItem.findFirst({ where: { id, userId } });
    if (!item) {
      throw AppError.notFound('Content item not found');
    }
    
    const updated = await app.prisma.contentItem.update({
      where: { id },
      data: {
        ...data,
        tags: data.tags ? {
          set: data.tags.map(name => ({ userId_name: { userId, name } })),
        } : undefined,
      },
      include: { tags: true },
    });
    
    return {
      success: true,
      data: updated,
      meta: {
        timestamp: new Date().toISOString(),
        requestId: request.id,
        version: '1.0.0',
      },
    };
  });

  // Delete content item
  app.delete('/:id', async (request, reply) => {
    const { id } = request.params as { id: string };
    const userId = request.user!.id;
    
    const item = await app.prisma.contentItem.findFirst({ where: { id, userId } });
    if (!item) {
      throw AppError.notFound('Content item not found');
    }
    
    await app.prisma.contentItem.delete({ where: { id } });
    
    return {
      success: true,
      data: { message: 'Content item deleted' },
      meta: {
        timestamp: new Date().toISOString(),
        requestId: request.id,
        version: '1.0.0',
      },
    };
  });

  // Bulk delete
  app.delete('/', {
    schema: {
      body: z.object({ ids: z.array(z.string().uuid()).min(1).max(100) }),
    },
  }, async (request, reply) => {
    const { ids } = request.body as { ids: string[] };
    const userId = request.user!.id;
    
    const result = await app.prisma.contentItem.deleteMany({
      where: { id: { in: ids }, userId },
    });
    
    return {
      success: true,
      data: { deletedCount: result.count },
      meta: {
        timestamp: new Date().toISOString(),
        requestId: request.id,
        version: '1.0.0',
      },
    };
  });

  // Get content stats
  app.get('/stats/overview', async (request, reply) => {
    const userId = request.user!.id;
    
    const [total, bySourceType, byStatus, recentCount] = await Promise.all([
      app.prisma.contentItem.count({ where: { userId } }),
      app.prisma.contentItem.groupBy({ by: ['sourceType'], where: { userId }, _count: true }),
      app.prisma.contentItem.groupBy({ by: ['status'], where: { userId }, _count: true }),
      app.prisma.contentItem.count({
        where: {
          userId,
          createdAt: { gte: new Date(Date.now() - 7 * 24 * 60 * 60 * 1000) },
        },
      }),
    ]);
    
    return {
      success: true,
      data: {
        total,
        recentCount,
        bySourceType: bySourceType.reduce((acc, item) => {
          acc[item.sourceType] = item._count;
          return acc;
        }, {} as Record<string, number>),
        byStatus: byStatus.reduce((acc, item) => {
          acc[item.status] = item._count;
          return acc;
        }, {} as Record<string, number>),
      },
      meta: {
        timestamp: new Date().toISOString(),
        requestId: request.id,
        version: '1.0.0',
      },
    };
  });
}