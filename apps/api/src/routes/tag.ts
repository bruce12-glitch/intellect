import { FastifyInstance } from 'fastify';
import { z } from 'zod';
import { AppError } from '../utils/errors';

const createTagSchema = z.object({
  name: z.string().min(1).max(50),
  color: z.string().regex(/^#[0-9A-Fa-f]{6}$/).optional(),
});

const updateTagSchema = z.object({
  name: z.string().min(1).max(50).optional(),
  color: z.string().regex(/^#[0-9A-Fa-f]{6}$/).optional(),
});

export async function tagRoutes(app: FastifyInstance) {
  // Get all tags
  app.get('/', async (request, reply) => {
    const userId = request.user!.id;
    
    const tags = await app.prisma.tag.findMany({
      where: { userId },
      orderBy: [{ count: 'desc' }, { name: 'asc' }],
    });
    
    return {
      success: true,
      data: tags,
      meta: {
        timestamp: new Date().toISOString(),
        requestId: request.id,
        version: '1.0.0',
      },
    };
  });

  // Create tag
  app.post('/', {
    schema: {
      body: createTagSchema,
    },
  }, async (request, reply) => {
    const data = request.body as z.infer<typeof createTagSchema>;
    const userId = request.user!.id;
    
    const tag = await app.prisma.tag.create({
      data: {
        userId,
        name: data.name,
        color: data.color || '#3B82F6',
        isAutoGenerated: false,
      },
    });
    
    return reply.status(201).send({
      success: true,
      data: tag,
      meta: {
        timestamp: new Date().toISOString(),
        requestId: request.id,
        version: '1.0.0',
      },
    });
  });

  // Update tag
  app.patch('/:id', {
    schema: {
      body: updateTagSchema,
    },
  }, async (request, reply) => {
    const { id } = request.params as { id: string };
    const data = request.body as z.infer<typeof updateTagSchema>;
    const userId = request.user!.id;
    
    const tag = await app.prisma.tag.findFirst({ where: { id, userId } });
    if (!tag) {
      throw AppError.notFound('Tag not found');
    }
    
    const updated = await app.prisma.tag.update({
      where: { id },
      data,
    });
    
    return {
      success: true,
      data: updated,
      meta: {
        timestamp: new Date().toISOString(),
        requestId: request.id,
        version: '1.0.0',
      },
    };
  });

  // Delete tag
  app.delete('/:id', async (request, reply) => {
    const { id } = request.params as { id: string };
    const userId = request.user!.id;
    
    const tag = await app.prisma.tag.findFirst({ where: { id, userId } });
    if (!tag) {
      throw AppError.notFound('Tag not found');
    }
    
    await app.prisma.tag.delete({ where: { id } });
    
    return {
      success: true,
      data: { message: 'Tag deleted' },
      meta: {
        timestamp: new Date().toISOString(),
        requestId: request.id,
        version: '1.0.0',
      },
    };
  });

  // Merge tags
  app.post('/merge', {
    schema: {
      body: z.object({
        sourceTagIds: z.array(z.string().uuid()).min(2),
        targetTagId: z.string().uuid(),
      }),
    },
  }, async (request, reply) => {
    const { sourceTagIds, targetTagId } = request.body as { sourceTagIds: string[]; targetTagId: string };
    const userId = request.user!.id;
    
    // Verify all tags belong to user
    const tags = await app.prisma.tag.findMany({
      where: { id: { in: [...sourceTagIds, targetTagId] }, userId },
    });
    
    if (tags.length !== sourceTagIds.length + 1) {
      throw AppError.badRequest('Some tags not found or unauthorized');
    }
    
    // Update content items to use target tag
    await app.prisma.contentItem.updateMany({
      where: { tags: { some: { id: { in: sourceTagIds } } } },
      data: {
        tags: {
          disconnect: sourceTagIds.map(id => ({ id })),
          connect: { id: targetTagId },
        },
      },
    });
    
    // Delete source tags
    await app.prisma.tag.deleteMany({
      where: { id: { in: sourceTagIds } },
    });
    
    // Update target tag count
    const targetTag = await app.prisma.tag.findUnique({ where: { id: targetTagId } });
    const count = await app.prisma.contentItem.count({
      where: { tags: { some: { id: targetTagId } } },
    });
    
    await app.prisma.tag.update({
      where: { id: targetTagId },
      data: { count },
    });
    
    return {
      success: true,
      data: { message: 'Tags merged successfully' },
      meta: {
        timestamp: new Date().toISOString(),
        requestId: request.id,
        version: '1.0.0',
      },
    };
  });
}